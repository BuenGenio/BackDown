#!/usr/bin/env python3
"""docs/changelog/ from the release notes: one page per shipped release (scripts/release-notes/<tag>.md, for the
tags status.json lists as shipped), newest first, plus the group's landing page. Run it after a release ships:

    python3 tools/release-notes.py        # then python3 build.py

The pages carry the release's date, so the docs show when each was published, not when this ran.
"""
import datetime
import json
import re
import subprocess
import sys
from pathlib import Path

MK = Path(__file__).resolve().parent.parent
ROOT = MK.parent
NOTES = ROOT / 'scripts' / 'release-notes'
OUT = MK / 'docs' / 'changelog'
RELEASES = 'https://github.com/BuenGenio/backdown-releases/releases/tag/'


def version_key(v):
    m = re.match(r'v?(\d+)\.(\d+)\.(\d+)(?:-(alpha|beta|rc)\.(\d+))?', v)
    stage = {'alpha': 0, 'beta': 1, 'rc': 2, None: 3}[m[4]]
    return (int(m[1]), int(m[2]), int(m[3]), stage, int(m[5] or 0))


def markdown(text):
    # mdlite has no <https://…> autolinks, and headings start at h2 there (the title is the h1)
    text = re.sub(r'<(https?://[^>\s]+)>', lambda m: f'[{m[1]}]({m[1]})', text)
    return text.strip() + '\n'


def main():
    status = json.loads((MK / 'status.json').read_text(encoding='utf-8'))
    shipped = {s['version']: s['date'] for s in status['shipped']}
    # the current download (downloads.json) is shipped even when status.json hasn't caught up; notes for a later
    # version are a release being prepared, and stay out until it ships
    dl = json.loads((MK / 'downloads.json').read_text(encoding='utf-8'))
    current = max((f['version'] for p in dl['platforms'] for f in [p] if f.get('version')), key=version_key, default=None)
    tags = []
    for f in NOTES.glob('v*.md'):
        tag = f.stem
        if tag in shipped or (current and version_key(tag) <= version_key(current)):
            tags.append(tag)
            if tag not in shipped:  # the date it was committed here, lacking a status.json entry
                out = subprocess.run(['git', '-C', str(ROOT), 'log', '-1', '--format=%cs', '--', str(f.relative_to(ROOT))], capture_output=True, text=True).stdout.strip()
                shipped[tag] = out or datetime.date.today().isoformat()
    tags.sort(key=version_key, reverse=True)
    if not tags:
        sys.exit('no shipped release has notes in scripts/release-notes/')
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob('*.md'):
        old.unlink()
    for n, tag in enumerate(tags):
        text = (NOTES / f'{tag}.md').read_text(encoding='utf-8')
        lede = re.sub(r'\s+', ' ', text.strip().split('\n\n')[0]).strip()
        lede = re.sub(r'[*`]', '', lede)
        if len(lede) > 300:
            cut = lede[:300].rsplit('. ', 1)[0]
            lede = cut + '.' if len(cut) > 120 else lede[:297].rsplit(' ', 1)[0] + '…'
        version = tag.lstrip('v')
        if len(lede) < 90:  # a one-line summary is too little for a search snippet
            lede += f' The release notes of BackDown {version}, with its downloads and checksums.'
        head = ['---', f'title: BackDown {version}', f'nav: {version}', f'seo_title: BackDown {version} release notes · what changed',
                f'description: {lede}', f'order: {n}', f'date: {shipped[tag]}', '---', '',
                f'<!-- Generated by tools/release-notes.py from scripts/release-notes/{tag}.md. Edit that, and run it again. -->', '',
                f'Released {shipped[tag]} · [downloads and checksums on GitHub]({RELEASES}{tag}) · [Download page](/download/)', '']
        (OUT / f'{version}.md').write_text('\n'.join(head) + markdown(text), encoding='utf-8')
    latest = tags[0].lstrip('v')
    index = ['---', 'title: Release notes', 'nav: Release notes', 'seo_title: BackDown release notes: every version, what changed and when',
             f'description: What changed in each release of BackDown, newest first ({latest} is the latest), with the installers and checksums of each on GitHub.',
             'order: 0', '---', '',
             '<!-- Generated by tools/release-notes.py. Run it again after a release ships. -->', '',
             f'Every release of BackDown, newest first. The latest is **{latest}**; the [Download page](/download/) always has the current one, '
             f'and `backdown update` installs it, checking the release\'s signature first. Each page is that release\'s notes as published on '
             f'[GitHub]({RELEASES.rsplit("/", 2)[0]}).', '', '<!-- cards -->', '']
    (OUT / 'index.md').write_text('\n'.join(index), encoding='utf-8')
    print(f'docs/changelog: {len(tags)} releases, latest {latest}')


if __name__ == '__main__':
    main()
