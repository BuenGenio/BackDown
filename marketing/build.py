def press_readme(facts, shots, boiler):
    lines = ['BackDown press kit', '==================', '', f'{SITE}/press/', '']
    for n, words in boiler.items():
        lines += [f'In {n} words', '-' * len(f'In {n} words'), '', words, '']
    # plain text: a link keeps its address, unless its label already is one
    def plain_links(v):
        def one(m):
            url = m[1] if m[1].startswith(('http:', 'https:', 'mailto:')) else SITE + m[1]
            return m[2] if m[2] in url else f'{m[2]} ({url})'
        return text(re.sub(r'<a href="([^"]+)">([^<]+)</a>', one, v))
    lines += ['Facts', '-----', '']
    lines += [f'{k}: {plain_links(v)}' for k, v in facts] + ['']
    lines += ['Logos (logos/)', '--------------', '',
              'SVG and PNG, transparent. The "-dark" files are for dark backgrounds. The mark is orange #d8432b',
              '(#f0603f on dark), the lettering charcoal #17161b (ivory #f5f3ec on dark). Keep clear space of',
              'at least half the mark\'s height around it; please don\'t recolour, stretch or add effects.',
              'The wordmark is set in Bricolage Grotesque (ExtraBold).', '',
              'Screenshots (screenshots/)', '--------------------------', '',
              'Real BackDown screens, shown with demo data, 2400 px wide, in light and dark:', '']
    lines += [f'- {sid}: {text(title)}' for sid, title in shots] + ['']
    return '\n'.join(lines)


def press_kit(t, cfg, dl, status, latest_version, latest_date):
    """the press page's values, and public/press/backdown-press-kit.zip"""
    boiler = boilerplate(latest_version)
    for variant in (BOILERPLATE, boilerplate('1.0.0')):
        for n, words in variant.items():
            if len(words.split()) != n:
                sys.exit(f'press kit: the {n}-word boilerplate has {len(words.split())} words')
    logos = press_logos()
    facts = press_facts(t, cfg, dl, status, latest_version, latest_date)
    if not cfg.get('contact_email'):
        print('note: site.json contact_email is empty, so the press kit names no press contact')
    shots = [(sid, t[f'slides.{sid}_title']) for sid, _ in SLIDES]
    # a zip that only changes when its contents do: fixed entry dates (the status page's date), fixed order
    stamp = tuple(int(x) for x in status['updated'].split('-')) + (0, 0, 0)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as z:
        def add(name, data, compress=True):
            info = zipfile.ZipInfo(f'backdown-press-kit/{name}', date_time=stamp)
            info.compress_type = zipfile.ZIP_DEFLATED if compress else zipfile.ZIP_STORED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
        add('README.txt', press_readme(facts, shots, boiler))
        for name, _, _ in LOGOS:
            add(f'logos/{name}.svg', logos[name].read_bytes())
            png = PRESS / 'logos' / f'{name}.png'
            if png.exists():
                add(f'logos/{name}.png', png.read_bytes(), compress=False)
        for sid, _ in shots:
            for theme in ('light', 'dark'):
                add(f'screenshots/{sid}-{theme}.webp', (ROOT / 'public/shots/en' / f'{sid}-{theme}-2400.webp').read_bytes(), compress=False)
    data = buf.getvalue()
    zpath = ROOT / 'public' / PRESS_ZIP
    if not zpath.exists() or zpath.read_bytes() != data:
        zpath.write_bytes(data)
    zip_v = hashlib.sha256(data).hexdigest()[:10]
    print(f'press: {PRESS_ZIP} ({human_size(len(data))})')

    boiler = ''.join(f'''   <article class="bp card"><div class="bp-head"><h3>In {n} words</h3><button class="btn btn-ghost sm copy" type="button" data-copy="#bp{n}" hidden>Copy</button></div>
    <p id="bp{n}">{esc(words)}</p></article>\n''' for n, words in boiler.items())
    facts_html = ''.join(f'<div><dt>{k}</dt><dd>{v}</dd></div>' for k, v in facts)

    def logo_card(name, label, bg):
        png = PRESS / 'logos' / f'{name}.png'
        links = [f'<a href="/press/logos/{name}.svg" download>SVG</a>']
        if png.exists():
            links.append(f'<a href="/press/logos/{name}.png" download>PNG</a>')
        return (f'<figure class="logo card"><div class="logo-bg {bg}"><img src="/press/logos/{name}.svg?v={BRAND_VERSION}" alt="{esc(label)}" loading="lazy"></div>'
                f'<figcaption><span>{esc(label)}</span><span class="dl-links">{" · ".join(links)}</span></figcaption></figure>')
    logos_html = ''.join(logo_card(*l) for l in LOGOS)
    shots_html = ''.join(
        f'<figure class="shot"><a href="/shots/en/{sid}-light-2400.webp" class="frame card"><picture>'
        f'<source media="(prefers-color-scheme: dark)" srcset="/shots/en/{sid}-dark-960.webp?v={BRAND_VERSION}">'
        f'<img src="/shots/en/{sid}-light-960.webp?v={BRAND_VERSION}" width="960" height="600" alt="{esc(t[f"slides.{sid}_alt"])}" loading="lazy" decoding="async"></picture></a>'
        f'<figcaption><b>{title}</b> <a href="/shots/en/{sid}-light-2400.webp">Light</a> · <a href="/shots/en/{sid}-dark-2400.webp">Dark</a></figcaption></figure>'
        for sid, title in shots)
    return {'@press_boiler': boiler, '@press_facts': facts_html, '@press_logos': logos_html, '@press_shots': shots_html,
            '@press_zip': f'/{PRESS_ZIP}?v={zip_v}', '@press_zip_size': human_size(len(data))}


def sitemap(pages, status, docs, page_dates):
    today = datetime.date.today().isoformat()
    urls = []
    for page in pages + docs:
        if page.get('noindex'):
            continue
        variants = langs_of(page)
        alts = ''.join(f'\n    <xhtml:link rel="alternate" hreflang="{tag(l)}" href="{SITE}{url_path(l, page)}"/>' for l in variants)
        alts += f'\n    <xhtml:link rel="alternate" hreflang="x-default" href="{SITE}{url_path("en", page)}"/>'
        def lastmod(l):
            if page['id'] == 'status':
                return status['updated']
            return page.get('date') or page_dates.get((page['id'], l), today)
        urls += [f'\n  <url>\n    <loc>{SITE}{url_path(l, page)}</loc>\n    <lastmod>{lastmod(l)}</lastmod>'
                 f'\n    <changefreq>{page["changefreq"]}</changefreq>\n    <priority>{page["priority"]}</priority>{alts}\n  </url>'
                 for l in variants]
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">'
            f'{"".join(urls)}\n</urlset>\n')


