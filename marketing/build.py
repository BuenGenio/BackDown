def docs_jsonld(docs, d, meta, lang, t):
    url = SITE + d['url']
    kind = 'CollectionPage' if d['home'] or d['landing'] else 'TechArticle'
    page = {'@type': kind, '@id': f'{url}#page', 'url': url, 'name': text(d['title']), 'headline': text(d['title']),
            'description': text(mdlite.inline(d['description'])), 'inLanguage': tag(lang), 'isPartOf': {'@id': f'{SITE}/#website'},
            'publisher': {'@id': f'{SITE}/#org'}, 'dateModified': d['date'], 'datePublished': d.get('published') or d['date'], 'image': meta['og_image'],
            'breadcrumb': {'@id': f'{url}#breadcrumb'}}
    if kind == 'TechArticle':
        page['author'] = {'@id': f'{SITE}/#org'}
        page['about'] = {'@type': 'SoftwareApplication', 'name': 'BackDown', 'applicationCategory': 'UtilitiesApplication',
                         'operatingSystem': 'Linux, macOS, Windows'}
    trail = [('BackDown', '/')] + docs_trail(docs, d, t, lang)
    crumbs = {'@type': 'BreadcrumbList', '@id': f'{url}#breadcrumb', 'itemListElement': [
        {'@type': 'ListItem', 'position': n, 'name': name, 'item': SITE + href} for n, (name, href) in enumerate(trail, 1)]}
    return ld(graph_base() + [page, crumbs])


def search_index(docs):
    """[[url, page title, section heading, text], ...]: one entry per page intro and per h2 section"""
    entries = []
    for d in docs:
        body = re.sub(r'<a class="hash"[^>]*>#</a>', '', d['body'].replace('<!-- cards -->', ''))
        parts = re.split(r'<h2 id="([^"]+)">(.*?)</h2>', body)
        entries.append([d['url'], text(d['title']), '', mdlite.plain(mdlite.inline(d['description']) + ' ' + parts[0])])
        for k in range(1, len(parts), 3):
            entries.append([f'{d["url"]}#{parts[k]}', text(d['title']), mdlite.plain(parts[k + 1]), mdlite.plain(parts[k + 2])])
    return json.dumps(entries, ensure_ascii=False, separators=(',', ':'))


# The docs' live demo: public/demo/ is BackDown's own web UI answered from recorded responses (made by
# tools/demo/, see its README). A guide embeds it with one raw block, `<figure class="demo" data-view="places"
# data-caption="…"></figure>`, which becomes a frame of the demo opened on that view (data-view), folder
# (data-dir, the fictional machine's path) and layout (data-mode: grid, list, gallery or treemap).
DEMO_FIGURE = re.compile(r'<figure class="demo"([^>]*)>\s*</figure>')
DEMO_ATTR = re.compile(r'data-(view|dir|mode|caption)="([^"]*)"')


def demo_version():
    f = ROOT / 'public/demo/d/index.json'
    return hashlib.sha256(f.read_bytes()).hexdigest()[:10] if f.exists() else 'none'


def demo_figures(body, lang, t):
    if '<figure class="demo"' not in body:
        return body
    v = demo_version()

    def figure(m):
        a = dict(DEMO_ATTR.findall(m.group(1)))
        params = [('v', v)] + ([('lang', lang)] if lang != 'en' else []) + [(k, a[k]) for k in ('view', 'dir', 'mode') if a.get(k)]
        src = '/demo/?' + '&amp;'.join(f'{k}={quote(v, safe="")}' for k, v in params)
        caption = mdlite.inline(html.unescape(a.get('caption', '')))
        return (f'<figure class="demo"><div class="demo-frame"><iframe src="{src}" title="{t["docs.demo_title"]}" loading="lazy" '
                f'referrerpolicy="same-origin"></iframe></div>'
                f'<figcaption>{caption}{" · " if caption else ""}<span class="demo-tag">{t["docs.demo_tag"]}</span> '
                f'<a href="{src}" target="_blank" rel="noopener">{t["docs.demo_open"]} ↗</a></figcaption></figure>')
    return DEMO_FIGURE.sub(figure, body)


def build_docs(base, docs_template, t, g, lang, docs_raw):
    docs = localize_docs(docs_raw, lang)
    index = search_index(docs)
    docs_root = ROOT / 'public' / ('docs' if lang == 'en' else f'{lang}/docs')
    docs_url = '/docs/' if lang == 'en' else f'/{lang}/docs/'
    docs_root.mkdir(parents=True, exist_ok=True)
    (docs_root / 'search.json').write_text(index, encoding='utf-8')
    index_v = hashlib.sha256(index.encode()).hexdigest()[:10]
    template = base.replace('{{@main}}', docs_template.rstrip('\n'))
    mark = lambda x: ' hreflang="en"' if x.get('cross_lang') else ''
    written = set()
    for n, d in enumerate(docs):
        if not d['translated']:
            continue
        title = t['docs.title_home'] if d['home'] else d.get('seo_title') or f'{text(d["title"])} {t["docs.meta_suffix"]}'
        desc = text(mdlite.inline(d['description']))
        meta = dict(title=title, description=desc, og_title=title, og_description=desc, og_alt=t['docs.og_alt'],
                    og_image=f'{SITE}/og/{d["card"]}.png?v={BRAND_VERSION}', crumb=text(d['title']))
        computed = shell(lang, d, t, meta, d['langs'], g)
        trail = docs_trail(docs, d, t, lang)
        crumbs = ''.join(f'<li><a href="{h}">{esc(name)}</a></li>' if k < len(trail) - 1 else f'<li><span aria-current="page">{esc(name)}</span></li>'
                         for k, (name, h) in enumerate(trail))
        toc, toc_fold = docs_toc(d, t)
        prev, nxt = (docs[n - 1] if n > 0 else None), (docs[n + 1] if n + 1 < len(docs) else None)
        pn = ''.join(f'<a class="pn card {cls}" href="{x["url"]}" rel="{rel}"{mark(x)}><span>{label}</span><b>{esc(text(x["title"]))}</b></a>'
                     for x, cls, rel, label in ((prev, 'prev', 'prev', t['docs.previous']), (nxt, 'next', 'next', t['docs.next'])) if x)
        cards = docs_cards(docs, t) if d['home'] else group_cards(docs, d['group'], t) if d['landing'] else ''
        body = demo_figures(d['body'].replace('<!-- cards -->', cards), lang, t)
        nav = docs_nav(docs, d, t)
        here = text(d['title']) if d['home'] or d['landing'] else f'{group_title(t, d["group"])} · {text(d["title"])}'
        computed.update({
            '@jsonld': docs_jsonld(docs, d, meta, lang, t),
            '@docs_nav': nav, '@docs_here': esc(here), '@docs_index': f'{docs_url}search.json?v={index_v}',
            '@docs_crumbs': crumbs, '@docs_title': mdlite.inline(d['title']) if not d['file'].startswith('docs/cli/') or d['landing'] else f'<code>{esc(d["title"])}</code>',
            '@docs_lede': mdlite.inline(d['description']), '@docs_badge': f' {preview_badge(t)}' if d['preview'] else '',
            '@docs_body': body, '@docs_toc': toc, '@docs_toc_fold': toc_fold, '@docs_pn': pn,
            '@docs_date': d['date'], '@docs_date_h': human_date(t, d['date']), '@docs_wide': ' has-toc' if toc else '',
        })
        out = fill(template, computed, t, d['file'])
        written.add(write_page(d['url'], out, f'{d["file"]} + templates/docs.html'))
    # pages whose source is gone, or (the uk pass) no longer translated
    for old in docs_root.rglob('index.html'):
        if old not in written:
            old.unlink()
            for parent in old.parents:
                if parent == docs_root or any(parent.iterdir()):
                    break
                parent.rmdir()
            print(f'removed {old.relative_to(ROOT)}')
    translated = [d for d in docs if d['translated']]
    previews = sum(1 for d in translated if d['preview'])
    print(f'docs ({lang}): {len(translated)} pages ({previews} marked next preview), search index {len(index) // 1024} KB')


