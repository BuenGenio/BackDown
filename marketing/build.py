def snippet(s, limit):
    """a meta description that fits a search result: whole sentences up to `limit` characters, else a clean cut"""
    s = re.sub(r'\s+', ' ', text(s)).strip()
    if len(s) <= limit:
        return s
    cut = s[:limit]
    for sep in ('. ', '; ', ': ', ', '):
        i = cut.rfind(sep)
        if i >= limit * 0.55:
            return cut[:i + 1] if sep == '. ' else cut[:i].rstrip(' ,;:') + '…'
    return cut.rsplit(' ', 1)[0].rstrip(' ,;:') + '…'


def shell(lang, page, t, meta, variants, g):
    """what base.html needs on every page: head tags, header, language menu, footer"""
    pid = page['id']
    href = href_map(lang)
    tabs = [(p['id'], href[p['id']]) for p in PAGES if p['nav']] + [('docs', href['docs'])]
    # links from a translated page to an English-only one say so (docs has its own, narrower language list)
    en = lambda i: ' hreflang="en"' if lang != 'en' and ((i == 'docs' and lang not in DOCS_LANGS) or langs_of(next((p for p in PAGES if p['id'] == i), {})) == ['en']) else ''
    nav = ''.join(f'<a href="{h}" data-p="{i}"{en(i)}{" aria-current=page" if i == pid else ""}>{t["nav." + i]}</a>' for i, h in tabs)
    foot = [(h, t['nav.' + i], en(i)) for i, h in tabs]
    foot.append((href['privacy'], t['footer.privacy_link'], ''))
    if g['cfg']['preorder']['enabled']:
        foot.append((href['terms'], t['footer.terms_link'], en('terms')))
    foot.append((href['press'], t['footer.press'], en('press')))
    foot.append((g['dl']['releases_url'], t['footer.releases'], ''))
    menu = ''.join(
        '<li><a href="{}" hreflang="{}" lang="{}"{}>{}{}</a></li>'.format(
            url_path(other, page if other in variants else PAGES[0]), tag(other), tag(other),
            ' aria-current="page"' if other == lang else '', flag(other), html.escape(g['tables'][other]['lang.name']))
        for other in LANGS)
    if variants == ['en']:
        menu = f'<li class="lang-note">{ENGLISH_ONLY}</li>' + menu
    alternates = '\n'.join(
        [f'<link rel="alternate" hreflang="{tag(l)}" href="{SITE}{url_path(l, page)}">' for l in variants]
        + [f'<link rel="alternate" hreflang="x-default" href="{SITE}{url_path("en", page)}">'])
    analytics = g['cfg']['analytics']
    tokens = g['cfg'].get('search', {}).get('verification', {})
    verification = '\n'.join(f'<meta name="{n}" content="{esc(v)}">' for n, v in
                             (('google-site-verification', tokens.get('google', '')), ('msvalidate.01', tokens.get('bing', ''))) if v)
    return {
        '@verification': verification,
        '@lang': tag(lang), '@page': lang, '@page_id': pid, '@code': lang.split('-')[0].upper(),
        '@url': SITE + url_path(lang, page), '@home': href['home'], '@asset_v': g['version'],
        '@brand_v': BRAND_VERSION, '@brand_mark': BRAND_INLINE,
        '@title': esc(meta['title']), '@description': esc(snippet(meta['description'], 155)),
        '@og_title': esc(text(meta['og_title'])), '@og_description': esc(snippet(meta['og_description'], 200)),
        '@og_image': meta['og_image'], '@og_image_alt': esc(text(meta['og_alt'])),
        '@robots': 'noindex, follow' if page.get('noindex') else 'index, follow, max-image-preview:large, max-snippet:-1',
        '@alternates': alternates, '@langmenu': menu, '@flag': flag(lang), '@nav': nav,
        '@og_alternates': '\n'.join(f'<meta property="og:locale:alternate" content="{g["tables"][o]["meta.og_locale"]}">'
                                    for o in variants if o != lang),
        '@footer_nav': ''.join(f'<a href="{esc(h)}"{attr}>{label}</a>' for h, label, attr in foot),
        '@footer_privacy': t['footer.privacy_analytics' if g['tracking'] else 'footer.privacy'],
        '@cta_href': '#join' if page['join'] else href['home'] + '#join',
        '@analytics': (f'<meta name="analytics" content="matomo" data-url="{esc(analytics["matomo_url"])}" data-site="{int(analytics["site_id"])}">\n'
                       f'<link rel="dns-prefetch" href="{esc(analytics["matomo_url"])}">') if g['tracking'] else '',
        '@releases_url': g['dl']['releases_url'],
        '@support_url': esc(g['cfg']['support_url']), '@cup': CUP,
        **{f'@href.{k}': v for k, v in href.items()},
    }


def fill(template, computed, t, where):
    def sub(m):
        key, attr = m[1], m[2]
        if key.startswith('@'):
            if key not in computed:
                sys.exit(f'{where}: nothing computes {{{{{key}}}}}')
            value = computed[key]
        else:
            value = t[key]
        return esc(value) if attr else value
    return TOKEN.sub(sub, template)


def write_page(here, out, source):
    out = out.replace('<!doctype html>', f'<!doctype html>\n<!-- Generated by build.py from {source}. Edit those, not this file. -->', 1)
    dest = ROOT / 'public' / here.strip('/') / 'index.html'
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(out, encoding='utf-8')
    return dest


