def cli_preview(version):
    """the 0.x releases were command-line previews; 1.0 and its betas have the desktop app"""
    return version.lstrip('v').startswith('0.')


def boilerplate(version):
    old, new = BOILERPLATE_APP
    return BOILERPLATE if cli_preview(version) else {n: w.replace(old, new) for n, w in BOILERPLATE.items()}


def press_logos():
    """public/press/logos/*.svg from the brand masters; the PNGs next to them come from screenshots/press.mjs"""
    light = {'backdown-mark': (ROOT / 'public/brand/backdown-mark.svg').read_text(encoding='utf-8'),
             'backdown-wordmark': (ROOT / 'public/brand/backdown-wordmark.svg').read_text(encoding='utf-8'),
             'backdown-logo': (ROOT / 'public/brand/backdown-logo.svg').read_text(encoding='utf-8'),
             'backdown-icon': (ROOT / 'public/favicon.svg').read_text(encoding='utf-8')}
    # on dark: the site's dark-mode orange, and ivory for the lettering
    dark = lambda svg: svg.replace('#d8432b', '#f0603f').replace('#17161b', '#f5f3ec')
    out = PRESS / 'logos'
    out.mkdir(parents=True, exist_ok=True)
    files = {}
    for name, _, _ in LOGOS:
        svg = dark(light[name.removesuffix('-dark')]) if name.endswith('-dark') else light[name]
        svg = svg.strip() + '\n'
        path = out / f'{name}.svg'
        if not path.exists() or path.read_text(encoding='utf-8') != svg:
            path.write_text(svg, encoding='utf-8')
        files[name] = path
    missing = [n for n, _, _ in LOGOS if not (out / f'{n}.png').exists()]
    if missing:
        print(f'note: no PNG for {", ".join(missing)} yet: cd screenshots && npm run press')
    return files


def human_size(n):
    for unit in ('bytes', 'KB', 'MB', 'GB'):
        if n < 1000 or unit == 'GB':
            return f'{n:.0f} {unit}' if unit in ('bytes', 'KB') else f'{n:.1f} {unit}'
        n /= 1000


